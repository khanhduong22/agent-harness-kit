#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Generate gallery/index.html: every style in styles.csv previewed side by side.

The page is generated rather than hand-written so it cannot drift from the dataset.
A style added to styles.csv shows up on the next run; a style still marked
`Template Status = planned` is rendered as a labelled placeholder instead of an
iframe pointing at a file that does not exist.

Usage:  python3 diagram-director/gallery/build_gallery.py
        python3 diagram-director/gallery/build_gallery.py --check    # fail if index.html is stale

Serve the repo root (the iframes load ../templates/base/*.html by relative path):
        python3 -m http.server 3579 --bind 127.0.0.1
        open http://127.0.0.1:3579/gallery/
"""

import argparse
import csv
import html
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO / "scripts"))
from csv_schema import split_list  # noqa: E402 (path set above, same pattern as tests/run_smoke.py)

STYLES_CSV = REPO / "data" / "styles.csv"
OUT = Path(__file__).resolve().parent / "index.html"

# Columns surfaced on each card. Keeping this list short is deliberate: the gallery
# answers "which style do I want?", not "how do I build it" -- that is style-guides.md.
FACTS = [
    ("Best for", "Best For"),
    ("Avoid for", "Do Not Use For"),
    ("Typography", "Typography"),
    ("Motion", "Motion Affinity"),
]


def load_styles():
    with STYLES_CSV.open(newline="", encoding="utf-8") as fh:
        return list(csv.DictReader(fh))


def _pill(row):
    """Status pill: shipped styles link to a live preview, planned ones say so."""
    shipped = row.get("Template Status") == "shipped"
    label = "shipped" if shipped else "planned"
    return f'<span class="pill pill--{label}">{label}</span>'


def _card(row):
    sid = row["Style ID"]
    shipped = row.get("Template Status") == "shipped"
    esc = lambda k: html.escape(row.get(k, ""))

    if shipped:
        # The frame is scaled down rather than clipped: at 1:1 a 300px-tall window
        # cuts the template's legend mid-line, which reads as a broken page rather
        # than a thumbnail. SCALE and the iframe's logical size are paired in the
        # stylesheet -- change one and the other must follow.
        preview = (
            '<div class="card__viewport">'
            f'<iframe class="card__frame" src="../templates/base/{sid}.html" '
            f'loading="lazy" scrolling="no" '
            f'title="Live preview of the {esc("Name")} template"></iframe>'
            "</div>"
        )
        open_link = f'<a class="card__open" href="../templates/base/{sid}.html">open full size &rarr;</a>'
    else:
        preview = (
            '<div class="card__empty">'
            "<p>No base template yet.</p>"
            "<p class=\"muted\">Compose from <code>templates/snippets/</code> "
            "plus this style's tokens in <code>references/style-guides.md</code>.</p>"
            "</div>"
        )
        open_link = ""

    def value(col):
        raw = row.get(col, "")
        if col == "Motion Affinity":
            # A raw pipe list is unreadable at a glance and can run to a dozen
            # entries; show the first few as prose and count the remainder.
            items = split_list(raw)
            head = ", ".join(items[:4])
            rest = len(items) - 4
            raw = f"{head} +{rest} more" if rest > 0 else head
        return html.escape(raw)

    facts = "".join(
        f"<dt>{html.escape(label)}</dt><dd>{value(col)}</dd>"
        for label, col in FACTS
        if row.get(col)
    )

    return f"""      <article class="card" id="{sid}">
        <header class="card__head">
          <h2 class="card__title">{esc("Name")} {_pill(row)}</h2>
          <p class="card__id"><code>{sid}</code> &middot; {esc("Runtime")}
             {"&middot; " + esc("CDN Deps") if row.get("CDN Deps") else ""}</p>
        </header>
        {preview}
        <p class="card__mood">{esc("Palette Mood")}</p>
        <dl class="card__facts">{facts}</dl>
        {open_link}
      </article>"""


